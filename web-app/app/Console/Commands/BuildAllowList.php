<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;

/**
 * Writes config/arc-commands.php: the v-* commands ArcCommand may run, taken
 * from the installed bin/ directory, less the root-only commands that sudo
 * does not allow arcpanelweb either (E39 W4 spec §9). v-add-sys-arcpanel runs
 * it on every install and upgrade.
 */
#[Signature('arcpanel:allow-list {--bin= : Directory with the v-* scripts (default: ../bin)} {--root-only= : List of root-only commands (default: ../install/common/sudo/root-only)} {--stdout : Print the file instead of writing it}')]
#[Description('Generate config/arc-commands.php from the v-* scripts in bin/')]
final class BuildAllowList extends Command
{
    public function handle(): int
    {
        $bin = $this->option('bin') ?: base_path('../bin');
        if (! is_dir($bin)) {
            $this->error("No bin directory at {$bin}");

            return self::FAILURE;
        }

        $rootOnly = $this->option('root-only') ?: base_path('../install/common/sudo/root-only');
        if (! is_file($rootOnly)) {
            $this->error("No list of root-only commands at {$rootOnly}");

            return self::FAILURE;
        }
        // One command per line; # starts a comment line
        $never = array_values(array_filter(array_map('trim', file($rootOnly) ?: []), fn (string $line) => $line !== '' && $line[0] !== '#'));

        $commands = [];
        foreach (scandir($bin) ?: [] as $file) {
            if (preg_match('/^v-[a-z0-9-]+$/', $file) === 1 && is_file($bin.'/'.$file) && ! in_array($file, $never, true)) {
                $commands[] = $file;
            }
        }
        sort($commands);

        $lines = array_map(fn (string $command) => "    '{$command}',", $commands);
        $body = "<?php\n\n// Generated by `php artisan arcpanel:allow-list`. Do not edit.\n\nreturn [\n".
            implode("\n", $lines)."\n];\n";
        // v-add-sys-arcpanel runs this as the web user and moves the output
        // into place itself: Laravel never boots as root (E39 W5 L15)
        if ($this->option('stdout')) {
            $this->output->write($body);

            return self::SUCCESS;
        }
        file_put_contents(config_path('arc-commands.php'), $body);

        $this->info(count($commands).' commands written to config/arc-commands.php');

        return self::SUCCESS;
    }
}
