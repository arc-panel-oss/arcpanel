<?php

namespace App\Http\Controllers\WebDomains;

use App\Arc\ExitCode;
use App\Auth\Principal;
use App\Http\Controllers\Controller;
use App\Policies\WebDomainPolicy;
use App\Services\QuickInstall\QuickInstallService;
use App\Services\WebDomains\WebDomainService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\View\View;

/**
 * Quick Install of a web application on a domain (web/add/webapp), run in
 * the background by the commands of E7 batch 2 spec §10.
 */
final class QuickInstallController extends Controller
{
    public function __construct(
        private readonly QuickInstallService $installs,
        private readonly WebDomainService $web,
    ) {}

    public function index(string $user, string $domain, Principal $principal, WebDomainPolicy $policy): View
    {
        abort_unless($policy->installApp($principal, $user), 403);
        $this->web->find($user, $domain);

        return view('web.install.index', [
            'user' => $user,
            'domain' => $domain,
            'apps' => $this->installs->apps(),
        ]);
    }

    public function form(string $user, string $domain, string $app, Principal $principal, WebDomainPolicy $policy): View|RedirectResponse
    {
        abort_unless($policy->installApp($principal, $user), 403);
        $this->web->find($user, $domain);
        $info = $this->installs->apps()[$app] ?? abort(404);
        if (! $info['installable']) {
            return redirect()->route('web.domains.install', ['user' => $user, 'domain' => $domain])
                ->with('error', sprintf(__('Unable to install %s, required php version is not available.'), $app));
        }
        $task = $this->installs->task($user);

        return view('web.install.form', [
            'user' => $user,
            'domain' => $domain,
            'app' => $info,
            'form' => $this->installs->form($user, $domain, $app),
            'task' => $task['domain'] === $domain && $task['app'] === $app ? $task : null,
            'busy' => $task['status'] === 'running',
        ]);
    }

    public function start(Request $request, string $user, string $domain, string $app, Principal $principal, WebDomainPolicy $policy): RedirectResponse
    {
        abort_unless($policy->installApp($principal, $user), 403);
        $this->web->find($user, $domain);
        abort_unless(isset($this->installs->apps()[$app]), 404);
        $form = $this->installs->form($user, $domain, $app);

        $input = (array) $request->input('options', []);
        $values = [];
        $errors = [];
        foreach ($form['fields'] as $field) {
            $raw = $input[$field['key']] ?? null;
            if (! is_null($raw) && ! is_scalar($raw)) {
                abort(422);
            }
            $value = $field['type'] === 'boolean' ? ($raw !== null && $raw !== '' ? 'true' : '') : trim((string) $raw);
            if (preg_match('/[\r\n\x00]/', $value) === 1) {
                $errors['options.'.$field['key']] = sprintf(__('Field "%s" can not be blank.'), $field['label']);

                continue;
            }
            if ($field['type'] === 'select' && $value !== '' && ! array_key_exists($value, $field['options'])) {
                abort(422);
            }
            if ($field['required'] && $value === '') {
                $errors['options.'.$field['key']] = sprintf(__('Field "%s" can not be blank.'), $field['label']);
            }
            // An empty optional password is generated by the installer
            if ($field['type'] !== 'password' || $value !== '') {
                $values[$field['key']] = $value;
            }
        }
        $back = redirect()->route('web.domains.install.form', ['user' => $user, 'domain' => $domain, 'app' => $app]);
        if ($errors !== []) {
            return $back->withErrors($errors)->withInput($request->except(self::passwordKeys($form)));
        }

        $result = $this->installs->start($user, $domain, $app, $values);
        if (! $result->ok()) {
            $message = $result->exit() === ExitCode::InUse ? __('Another installation is running for this account.') : $result->errorMessage();

            return $back->withInput($request->except(self::passwordKeys($form)))->with('error', $message);
        }

        return $back->with('ok', sprintf(__('Installing %s. This can take a few minutes.'), $app));
    }

    /** GET …/install-task: the user's install, for this domain only. */
    public function task(string $user, string $domain, Principal $principal, WebDomainPolicy $policy): JsonResponse
    {
        abort_unless($policy->installApp($principal, $user), 403);
        $task = $this->installs->task($user);
        if ($task['domain'] !== $domain) {
            $task = ['id' => '', 'domain' => $domain, 'app' => '', 'status' => '', 'exit' => '', 'start' => '', 'end' => '', 'log' => ''];
        }

        return response()->json(['task' => $task]);
    }

    /**
     * @param  array{fields: list<array{key: string, type: string}>}  $form
     * @return list<string>
     */
    private static function passwordKeys(array $form): array
    {
        return array_values(array_map(fn (array $field) => 'options.'.$field['key'],
            array_filter($form['fields'], fn (array $field) => $field['type'] === 'password')));
    }
}
