// Versions and changelog of a release line (docs/features/specs/2026-10-21-001-release-standards-design.md §7).
//
// Usage: npm run release -- <command>
//   check [--tag TAG]   the checks of spec §7.2; exit 1 with one line per failure
//   version VERSION     writes the version into the control file, both installers and src/release.json
//   open VERSION        opens the next version of a line: VERSION~alpha, src/release.json reset
//   cut [--date DATE]   the stable release: version, changelog/X.Y.Z.md from the fragments, CHANGELOG.md
//   changelog new <scope>-<slug> --type TYPE [--attention]
//                       creates a fragment in changelog/unreleased/
//   changelog build     writes CHANGELOG.md from changelog/header.md and the release files
//   changelog preview   prints the next release section from the fragments
//   changelog notes TAG prints the GitHub Release notes of a tag
//
// The tool never commits, tags or pushes. No dependencies, Node.js 22.
// RELEASE_ROOT replaces the repository root and RELEASE_BRANCH the current branch (tests).

import { execFileSync } from 'node:child_process';
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	unlinkSync,
	writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const FILES = {
	control: 'src/deb/arcpanel/control',
	debian: 'install/arcpanel-install-debian.sh',
	ubuntu: 'install/arcpanel-install-ubuntu.sh',
	metadata: 'src/release.json',
	changelog: 'changelog',
	header: 'changelog/header.md',
	unreleased: 'changelog/unreleased',
	built: 'CHANGELOG.md',
};

// Fragment types and the sections of a release, in the order of the changelog (spec §5.2, §5.3)
const SECTIONS = [
	['breaking', 'Breaking changes'],
	['security', 'Security'],
	['added', 'Added'],
	['changed', 'Changed'],
	['deprecated', 'Deprecated'],
	['removed', 'Removed'],
	['fixed', 'Fixed'],
];
const FRAGMENT_TYPES = [...SECTIONS.map(([type]) => type), 'summary'];
const FRAGMENT_NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)+\.md$/;
const RELEASE_HEADING_RE = /^## (\d+\.\d+\.\d+) — \d{4}-\d{2}-\d{2}(?: \([^)]+\))?$/;
const BUILT_NOTE =
	'<!-- Built by `npm run release -- changelog build` from changelog/; do not edit this file by hand. -->';
const UNRELEASED_NOTE =
	'Changes that are not released yet are in `changelog/unreleased/` of each release line.';

// X.Y.Z, X.Y.Z~alpha, X.Y.Z~beta.N, X.Y.Z~rc.N (spec §4.3)
const VERSION_RE = /^(\d+)\.(\d+)\.(\d+)(?:~(alpha|beta\.[1-9]\d*|rc\.[1-9]\d*))?$/;
const CONTROL_RE = /^Version: ([^\r\n]*)/m;
const INSTALLER_RE = /^ARCPANEL_INSTALL_VER='([^'\r\n]*)'/m;
const METADATA_KEYS = ['version', 'security', 'attention', 'attention_items', 'min_from'];

export class ReleaseError extends Error {}

export function parseVersion(version) {
	const match = VERSION_RE.exec(version ?? '');
	if (!match) {
		return null;
	}
	return {
		major: Number(match[1]),
		minor: Number(match[2]),
		patch: Number(match[3]),
		base: `${match[1]}.${match[2]}.${match[3]}`,
		pre: match[4] ?? null,
	};
}

// Debian version order (dpkg's verrevcmp): "~" sorts before everything, even the end of the string
function order(char) {
	if (char === undefined) {
		return 0;
	}
	if (char === '~') {
		return -1;
	}
	if (/[A-Za-z]/.test(char)) {
		return char.charCodeAt(0);
	}
	return char.charCodeAt(0) + 256;
}

function compareFragment(a, b) {
	let i = 0;
	let j = 0;
	while (i < a.length || j < b.length) {
		let firstDiff = 0;
		while ((i < a.length && !/\d/.test(a[i])) || (j < b.length && !/\d/.test(b[j]))) {
			const ac = i < a.length && !/\d/.test(a[i]) ? a[i] : undefined;
			const bc = j < b.length && !/\d/.test(b[j]) ? b[j] : undefined;
			const diff = order(ac) - order(bc);
			if (diff) {
				return Math.sign(diff);
			}
			i++;
			j++;
		}
		while (a[i] === '0') {
			i++;
		}
		while (b[j] === '0') {
			j++;
		}
		while (i < a.length && /\d/.test(a[i]) && j < b.length && /\d/.test(b[j])) {
			if (!firstDiff) {
				firstDiff = a.charCodeAt(i) - b.charCodeAt(j);
			}
			i++;
			j++;
		}
		if (i < a.length && /\d/.test(a[i])) {
			return 1;
		}
		if (j < b.length && /\d/.test(b[j])) {
			return -1;
		}
		if (firstDiff) {
			return Math.sign(firstDiff);
		}
	}
	return 0;
}

function splitDebian(version) {
	const colon = version.indexOf(':');
	const epoch = colon > 0 ? Number(version.slice(0, colon)) : 0;
	const rest = colon > 0 ? version.slice(colon + 1) : version;
	const dash = rest.lastIndexOf('-');
	return dash > 0
		? { epoch, upstream: rest.slice(0, dash), revision: rest.slice(dash + 1) }
		: { epoch, upstream: rest, revision: '' };
}

export function compareVersions(a, b) {
	const left = splitDebian(a);
	const right = splitDebian(b);
	if (left.epoch !== right.epoch) {
		return Math.sign(left.epoch - right.epoch);
	}
	return (
		compareFragment(left.upstream, right.upstream) || compareFragment(left.revision, right.revision)
	);
}

function read(root, file) {
	return readFileSync(join(root, file), 'utf8');
}

function readVersion(root, file, pattern) {
	if (!existsSync(join(root, file))) {
		throw new ReleaseError(`${file} does not exist`);
	}
	const match = pattern.exec(read(root, file));
	if (!match) {
		throw new ReleaseError(`${file} has no version line`);
	}
	return match[1];
}

// Replaces the version on its line and keeps every other byte of the file
function writeVersion(root, file, pattern, line) {
	const text = read(root, file);
	if (!pattern.test(text)) {
		throw new ReleaseError(`${file} has no version line`);
	}
	writeFileSync(join(root, file), text.replace(pattern, line));
}

export function readMetadata(root) {
	try {
		return JSON.parse(read(root, FILES.metadata));
	} catch (error) {
		throw new ReleaseError(`${FILES.metadata} cannot be read: ${error.message}`);
	}
}

function writeMetadata(root, metadata) {
	const ordered = Object.fromEntries(METADATA_KEYS.map((key) => [key, metadata[key]]));
	writeFileSync(join(root, FILES.metadata), `${JSON.stringify(ordered, null, '\t')}\n`);
}

export function readVersions(root) {
	return {
		control: readVersion(root, FILES.control, CONTROL_RE),
		debian: readVersion(root, FILES.debian, INSTALLER_RE),
		ubuntu: readVersion(root, FILES.ubuntu, INSTALLER_RE),
	};
}

function writeVersions(root, version) {
	writeVersion(root, FILES.control, CONTROL_RE, `Version: ${version}`);
	writeVersion(root, FILES.debian, INSTALLER_RE, `ARCPANEL_INSTALL_VER='${version}'`);
	writeVersion(root, FILES.ubuntu, INSTALLER_RE, `ARCPANEL_INSTALL_VER='${version}'`);
}

export function currentBranch(root) {
	if (process.env.RELEASE_BRANCH !== undefined) {
		return process.env.RELEASE_BRANCH || null;
	}
	try {
		const branch = execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'], {
			cwd: root,
			encoding: 'utf8',
			stdio: ['ignore', 'pipe', 'ignore'],
		}).trim();
		return branch && branch !== 'HEAD' ? branch : null;
	} catch {
		return null;
	}
}

// The release files of changelog/: X.Y.Z.md
export function releaseFiles(root) {
	const dir = join(root, FILES.changelog);
	if (!existsSync(dir)) {
		return [];
	}
	return readdirSync(dir, { withFileTypes: true })
		.filter((entry) => entry.isFile() && /^\d+\.\d+\.\d+\.md$/.test(entry.name))
		.map((entry) => entry.name.slice(0, -3))
		.sort((a, b) => compareVersions(b, a));
}

function names(fragments) {
	return fragments.map((fragment) => fragment.name).join(', ');
}

function isVersionString(value) {
	return typeof value === 'string' && parseVersion(value) !== null;
}

function lf(text) {
	return text.replace(/\r\n/g, '\n');
}

// A fragment: front matter (type, attention, order) and a body of bullets, or one paragraph for a summary
export function parseFragment(name, text) {
	if (!FRAGMENT_NAME_RE.test(name)) {
		throw new ReleaseError(`${name}: the name is not <scope>-<slug>.md in lower-case kebab case`);
	}
	const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(lf(text));
	if (!match) {
		throw new ReleaseError(`${name}: no front matter between --- lines`);
	}
	const fields = {};
	for (const line of match[1].split('\n')) {
		const field = /^([a-z_]+): *(.*?) *$/.exec(line);
		if (!field || !['type', 'attention', 'order'].includes(field[1]) || field[1] in fields) {
			throw new ReleaseError(`${name}: unknown or repeated front matter line "${line}"`);
		}
		fields[field[1]] = field[2];
	}
	if (!FRAGMENT_TYPES.includes(fields.type)) {
		throw new ReleaseError(`${name}: type must be one of ${FRAGMENT_TYPES.join(', ')}`);
	}
	if (fields.attention !== undefined && !['true', 'false'].includes(fields.attention)) {
		throw new ReleaseError(`${name}: attention must be true or false`);
	}
	if (fields.order !== undefined && !/^-?\d+$/.test(fields.order)) {
		throw new ReleaseError(`${name}: order must be a whole number`);
	}
	const body = match[2].trim();
	if (body === '') {
		throw new ReleaseError(`${name}: the body is empty`);
	}
	if (/^#/m.test(body)) {
		throw new ReleaseError(`${name}: the body must not contain headings`);
	}
	if (fields.type === 'summary' && (body.startsWith('- ') || body.includes('\n\n'))) {
		throw new ReleaseError(`${name}: a summary is one paragraph without a bullet`);
	}
	if (fields.type !== 'summary' && !body.startsWith('- ')) {
		throw new ReleaseError(`${name}: the body must start with a top-level bullet "- "`);
	}
	return {
		name,
		type: fields.type,
		attention: fields.attention === 'true',
		order: fields.order === undefined ? 100 : Number(fields.order),
		body,
	};
}

// The fragments of changelog/unreleased/ and the reasons the others were refused
export function readFragments(root) {
	const dir = join(root, FILES.unreleased);
	const fragments = [];
	const failures = [];
	if (!existsSync(dir)) {
		return { fragments, failures };
	}
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.name === '.gitkeep') {
			continue;
		}
		try {
			if (!entry.isFile()) {
				throw new ReleaseError(`${entry.name}: not a fragment file`);
			}
			fragments.push(parseFragment(entry.name, read(root, `${FILES.unreleased}/${entry.name}`)));
		} catch (error) {
			if (!(error instanceof ReleaseError)) {
				throw error;
			}
			failures.push(`${FILES.unreleased}/${error.message}`);
		}
	}
	fragments.sort((a, b) => a.order - b.order || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
	return { fragments, failures };
}

function fragmentsOrFail(root) {
	const { fragments, failures } = readFragments(root);
	if (failures.length) {
		throw new ReleaseError(failures.join('\n'));
	}
	return fragments;
}

// The body of a release section: the summary, then one section per type (spec §5.3)
export function sectionBody(fragments) {
	const blocks = fragments
		.filter((fragment) => fragment.type === 'summary')
		.map((fragment) => fragment.body);
	for (const [type, title] of SECTIONS) {
		const entries = fragments.filter((fragment) => fragment.type === type);
		if (entries.length) {
			blocks.push(`### ${title}\n\n${entries.map((fragment) => fragment.body).join('\n')}`);
		}
	}
	return blocks.join('\n\n');
}

function releaseSection(heading, fragments) {
	const body = sectionBody(fragments);
	return body ? `${heading}\n\n${body}\n` : `${heading}\n`;
}

// CHANGELOG.md: the note, changelog/header.md, the unreleased note, the release files newest first
export function buildChangelog(root) {
	if (!existsSync(join(root, FILES.header))) {
		throw new ReleaseError(`${FILES.header} does not exist`);
	}
	const parts = [BUILT_NOTE, lf(read(root, FILES.header)).trim(), UNRELEASED_NOTE];
	for (const version of releaseFiles(root)) {
		parts.push(lf(read(root, `${FILES.changelog}/${version}.md`)).trim());
	}
	return `${parts.join('\n\n')}\n`;
}

// Each check returns its failures, one line each (spec §7.2)
export function runChecks(root, { tag = null, branch = currentBranch(root) } = {}) {
	const failures = [];
	let versions;
	let metadata;
	try {
		versions = readVersions(root);
	} catch (error) {
		failures.push(`C1 ${error.message}`);
	}
	try {
		metadata = readMetadata(root);
	} catch (error) {
		failures.push(`C3 ${error.message}`);
	}
	if (!versions || !metadata) {
		return failures;
	}
	const { control } = versions;
	const parsed = parseVersion(control);

	// C1: one version in the control file and both installers
	if (versions.debian !== control || versions.ubuntu !== control) {
		failures.push(
			`C1 versions differ: ${FILES.control} ${control}, ${FILES.debian} ${versions.debian}, ${FILES.ubuntu} ${versions.ubuntu}`,
		);
	}
	if (!parsed) {
		failures.push(`C1 ${control} is not X.Y.Z, X.Y.Z~alpha, X.Y.Z~beta.N or X.Y.Z~rc.N`);
	}

	// C3: the release metadata of E33 §4
	const unknown = Object.keys(metadata).filter((key) => !METADATA_KEYS.includes(key));
	if (unknown.length) {
		failures.push(`C3 ${FILES.metadata} has unknown fields: ${unknown.join(', ')}`);
	}
	const metadataVersion = parseVersion(metadata.version);
	if (!metadataVersion || metadataVersion.pre === 'alpha') {
		failures.push(
			`C3 ${FILES.metadata} version ${metadata.version} is not X.Y.Z, X.Y.Z~beta.N or X.Y.Z~rc.N`,
		);
	}
	if (typeof metadata.security !== 'boolean') {
		failures.push(`C3 ${FILES.metadata} security is not true or false`);
	}
	if (typeof metadata.attention !== 'boolean') {
		failures.push(`C3 ${FILES.metadata} attention is not true or false`);
	}
	const items = metadata.attention_items;
	if (
		!Array.isArray(items) ||
		!items.every((item) => typeof item === 'string' && item.trim() !== '')
	) {
		failures.push(`C3 ${FILES.metadata} attention_items is not a list of sentences`);
	} else if (metadata.attention === true && items.length === 0) {
		failures.push(`C3 ${FILES.metadata} says attention: true without attention_items`);
	}
	if (metadata.min_from !== null && !isVersionString(metadata.min_from)) {
		failures.push(`C3 ${FILES.metadata} min_from ${metadata.min_from} is not a version or null`);
	}

	// C2: src/release.json names the version the line is heading for
	if (metadata.version !== control && `${metadata.version}~alpha` !== control) {
		failures.push(`C2 ${FILES.metadata} says ${metadata.version}, the control file ${control}`);
	}

	// C4: the branch fits the version
	const line = /^v(\d+)\.(\d+)\.x$/.exec(branch ?? '');
	if (parsed && line && (Number(line[1]) !== parsed.major || Number(line[2]) !== parsed.minor)) {
		failures.push(`C4 ${control} is not a version of the line ${branch}`);
	}
	if (parsed && branch === 'develop' && (parsed.patch !== 0 || parsed.pre !== 'alpha')) {
		failures.push(`C4 develop carries ${control}, expected X.Y.0~alpha`);
	}

	// C5: the tag matches the version
	if (tag !== null) {
		const expected = `v${control.replace('~', '-')}`;
		if (tag !== expected) {
			failures.push(
				`C5 tag ${tag} does not match the control version ${control} (expected ${expected})`,
			);
		}
		if (parsed?.pre === 'alpha') {
			failures.push(
				`C5 ${control} is a development version; set the release version before tagging`,
			);
		}
		if (parsed && !parsed.pre) {
			if (!existsSync(join(root, `${FILES.changelog}/${parsed.base}.md`))) {
				failures.push(
					`C5 ${FILES.changelog}/${parsed.base}.md does not exist; run npm run release -- cut`,
				);
			}
			if (readFragments(root).fragments.length) {
				failures.push(`C5 ${FILES.unreleased}/ still holds fragments at a stable tag`);
			}
		}
	}

	// C6: the fragments
	const { fragments, failures: fragmentFailures } = readFragments(root);
	failures.push(...fragmentFailures.map((failure) => `C6 ${failure}`));
	const summaries = fragments.filter((fragment) => fragment.type === 'summary');
	if (summaries.length > 1) {
		failures.push(`C6 more than one summary: ${names(summaries)}`);
	}

	// C7: a security fragment exactly when the release is a security release
	const security = fragments.filter((fragment) => fragment.type === 'security');
	if (metadata.security === true && !security.length) {
		failures.push(`C7 ${FILES.metadata} says security: true without a security fragment`);
	}
	if (metadata.security === false && security.length) {
		failures.push(`C7 ${names(security)} needs security: true in ${FILES.metadata}`);
	}

	// C8: fragments that need attention
	const attention = fragments.filter((fragment) => fragment.attention);
	if (attention.length && !(Array.isArray(items) && items.length)) {
		failures.push(`C8 ${names(attention)} needs attention_items in ${FILES.metadata}`);
	}
	const breaking = fragments.filter((fragment) => fragment.type === 'breaking');
	const patch = metadataVersion && metadataVersion.patch > 0;
	if (patch && (attention.length || breaking.length) && metadata.attention !== true) {
		failures.push(
			`C8 a patch release with ${names([...new Set([...attention, ...breaking])])} needs attention: true`,
		);
	}

	// C9: CHANGELOG.md is the built one
	try {
		const built = buildChangelog(root);
		const current = existsSync(join(root, FILES.built)) ? lf(read(root, FILES.built)) : null;
		if (current !== built) {
			failures.push(
				`C9 ${FILES.built} differs from the build; run npm run release -- changelog build`,
			);
		}
	} catch (error) {
		if (!(error instanceof ReleaseError)) {
			throw error;
		}
		failures.push(`C9 ${error.message}`);
	}

	// C10: the release files
	const changelogDir = join(root, FILES.changelog);
	if (existsSync(changelogDir)) {
		for (const entry of readdirSync(changelogDir)) {
			if (
				!entry.startsWith('.') &&
				!['header.md', 'unreleased'].includes(entry) &&
				!/^\d+\.\d+\.\d+\.md$/.test(entry)
			) {
				failures.push(
					`C10 ${FILES.changelog}/${entry} is neither a release file X.Y.Z.md nor header.md`,
				);
			}
		}
	}
	const lineVersion = metadata.version;
	for (const version of releaseFiles(root)) {
		const file = `${FILES.changelog}/${version}.md`;
		const heading = read(root, file).split(/\r?\n/, 1)[0];
		const match = RELEASE_HEADING_RE.exec(heading);
		if (!match || match[1] !== version) {
			failures.push(`C10 ${file} does not start with "## ${version} — YYYY-MM-DD"`);
		}
		if (isVersionString(lineVersion) && compareVersions(version, lineVersion) > 0) {
			failures.push(`C10 ${file} is newer than the line's version ${lineVersion}`);
		}
	}
	return failures;
}

function commandCheck(root, args, out) {
	let tag = null;
	for (let i = 0; i < args.length; i++) {
		if (args[i] === '--tag' && args[i + 1]) {
			tag = args[++i];
		} else {
			throw new ReleaseError('usage: check [--tag TAG]');
		}
	}
	const failures = runChecks(root, { tag });
	if (failures.length) {
		for (const failure of failures) {
			out.error(`release: ${failure}`);
		}
		return 1;
	}
	const branch = currentBranch(root);
	out.log(
		`release: ${readVersions(root).control} passes${branch ? ` on ${branch}` : ''}${tag ? ` for ${tag}` : ''}`,
	);
	return 0;
}

export function setVersion(root, version) {
	const parsed = parseVersion(version);
	if (!parsed) {
		throw new ReleaseError(`${version} is not X.Y.Z, X.Y.Z~alpha, X.Y.Z~beta.N or X.Y.Z~rc.N`);
	}
	const metadata = readMetadata(root);
	writeVersions(root, version);
	writeMetadata(root, { ...metadata, version: parsed.pre === 'alpha' ? parsed.base : version });
}

export function openVersion(root, version) {
	const parsed = parseVersion(version);
	if (!parsed || parsed.pre) {
		throw new ReleaseError(`open takes a release version X.Y.Z, not ${version}`);
	}
	writeVersions(root, `${version}~alpha`);
	writeMetadata(root, {
		version,
		security: false,
		attention: false,
		attention_items: [],
		min_from: null,
	});
}

function single(args, usage) {
	if (args.length !== 1) {
		throw new ReleaseError(`usage: ${usage}`);
	}
	return args[0];
}

function none(args, usage) {
	if (args.length) {
		throw new ReleaseError(`usage: ${usage}`);
	}
}

function today() {
	const now = new Date();
	const pad = (value) => String(value).padStart(2, '0');
	return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

// The attention items of the release of a tag: src/release.json when it describes that version,
// else the file at the tag
function attentionItems(root, tag, version) {
	let metadata = readMetadata(root);
	if (metadata.version !== version) {
		try {
			metadata = JSON.parse(
				execFileSync('git', ['show', `${tag}:${FILES.metadata}`], {
					cwd: root,
					encoding: 'utf8',
					stdio: ['ignore', 'pipe', 'ignore'],
				}),
			);
		} catch {
			return [];
		}
	}
	return metadata.version === version && Array.isArray(metadata.attention_items)
		? metadata.attention_items
		: [];
}

// The notes of a GitHub Release (spec §5.6): a stable release from its release file, a beta or a
// release candidate from the fragments of its line
export function releaseNotes(root, tag) {
	const match = /^v(\d+\.\d+\.\d+)(?:-((?:beta|rc)\.[1-9]\d*))?$/.exec(tag);
	if (!match) {
		throw new ReleaseError(`${tag} is not vX.Y.Z, vX.Y.Z-beta.N or vX.Y.Z-rc.N`);
	}
	const [, base, pre] = match;
	const parts = [];
	if (!pre) {
		const file = `${FILES.changelog}/${base}.md`;
		if (!existsSync(join(root, file))) {
			throw new ReleaseError(`${file} does not exist`);
		}
		parts.push(
			lf(read(root, file))
				.trim()
				.replace(/^## [^\n]*\n+/, ''),
		);
		const items = attentionItems(root, tag, base);
		if (items.length) {
			parts.push(`**Before you update:** ${items.join(' ')}`);
		}
		parts.push(
			`Full changelog: https://github.com/arc-panel-oss/arcpanel/blob/${tag}/${FILES.built}`,
		);
	} else {
		const { major, minor, patch } = parseVersion(base);
		const previous =
			patch > 0
				? `${major}.${minor}.${patch - 1}`
				: `the ${minor > 0 ? `${major}.${minor - 1}` : `${major - 1}.x`} line`;
		const body = sectionBody(fragmentsOrFail(root));
		parts.push(`Changes since ${previous}:`, body || 'No changes listed yet.');
	}
	return `${parts.join('\n\n')}\n`;
}

export function writeChangelog(root) {
	writeFileSync(join(root, FILES.built), buildChangelog(root));
}

export function newFragment(root, name, type, attention) {
	if (!FRAGMENT_TYPES.includes(type)) {
		throw new ReleaseError(`--type must be one of ${FRAGMENT_TYPES.join(', ')}`);
	}
	const file = `${name}.md`;
	if (!FRAGMENT_NAME_RE.test(file)) {
		throw new ReleaseError(`${name} is not <scope>-<slug> in lower-case kebab case`);
	}
	const path = join(root, FILES.unreleased, file);
	if (existsSync(path)) {
		throw new ReleaseError(`${FILES.unreleased}/${file} exists already`);
	}
	// The hint fails the check until it is replaced by the entry
	const hint =
		type === 'summary'
			? '<!-- One paragraph: what this release is about, with links to its specs. -->'
			: '<!-- One or more top-level bullets "- …": what administrators, resellers, users or API clients notice. -->';
	mkdirSync(join(root, FILES.unreleased), { recursive: true });
	writeFileSync(
		path,
		`---\ntype: ${type}\n${attention ? 'attention: true\n' : ''}---\n\n${hint}\n`,
	);
	return `${FILES.unreleased}/${file}`;
}

// The stable release commit of the line (spec §7.1); prints what to review and the Git commands
export function cut(root, date, out) {
	const before = runChecks(root);
	if (before.length) {
		throw new ReleaseError(`fix these first:\n${before.join('\n')}`);
	}
	if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
		throw new ReleaseError(`--date ${date} is not YYYY-MM-DD`);
	}
	const fragments = fragmentsOrFail(root);
	if (!fragments.length) {
		throw new ReleaseError(`${FILES.unreleased}/ has no fragments; there is nothing to release`);
	}
	const metadata = readMetadata(root);
	const version = parseVersion(metadata.version).base;
	const file = `${FILES.changelog}/${version}.md`;
	if (existsSync(join(root, file))) {
		throw new ReleaseError(`${file} exists already`);
	}

	writeFileSync(join(root, file), releaseSection(`## ${version} — ${date}`, fragments));
	for (const fragment of fragments) {
		unlinkSync(join(root, FILES.unreleased, fragment.name));
	}
	setVersion(root, version);
	writeChangelog(root);

	const tag = `v${version}`;
	const after = runChecks(root, { tag });
	for (const failure of after) {
		out.error(`release: ${failure}`);
	}

	out.log(`release: ${file} written from ${fragments.length} fragments, version ${version} set`);
	const attention = fragments.filter((fragment) => fragment.attention);
	out.log('');
	out.log(`Fragments that need attention (${attention.length}):`);
	for (const fragment of attention) {
		out.log(`  ${fragment.name}: ${fragment.body.split('\n', 1)[0].slice(0, 120)}`);
	}
	out.log(`attention_items of ${FILES.metadata} (attention: ${metadata.attention}):`);
	for (const item of metadata.attention_items) {
		out.log(`  - ${item}`);
	}
	if (parseVersion(version).patch === 0) {
		out.log('  A minor or major release always waits for the administrator.');
	}
	const line = `v${version.split('.').slice(0, 2).join('.')}.x`;
	out.log('');
	out.log('Review the diff, then:');
	out.log(
		`  git add -A ${FILES.changelog} ${FILES.built} ${FILES.metadata} ${FILES.control} ${FILES.debian} ${FILES.ubuntu}`,
	);
	out.log(`  git commit -m "chore(release): set version ${version}"`);
	out.log(`  git tag -a ${tag} -m "ArcPanel ${version} (stable channel)"`);
	out.log(`  git push origin ${line} && git push origin ${tag}    # on a request of a PM or PL`);
	return after.length ? 1 : 0;
}

function parseNewArgs(args) {
	const options = { name: null, type: null, attention: false };
	for (let i = 0; i < args.length; i++) {
		if (args[i] === '--type' && args[i + 1]) {
			options.type = args[++i];
		} else if (args[i] === '--attention') {
			options.attention = true;
		} else if (options.name === null && !args[i].startsWith('-')) {
			options.name = args[i];
		} else {
			return null;
		}
	}
	return options.name && options.type ? options : null;
}

function changelog(root, args, out) {
	const [command, ...rest] = args;
	switch (command) {
		case 'new': {
			const options = parseNewArgs(rest);
			if (!options) {
				throw new ReleaseError('usage: changelog new <scope>-<slug> --type TYPE [--attention]');
			}
			const file = newFragment(root, options.name, options.type, options.attention);
			out.log(`release: ${file} created; replace its comment with the entry`);
			return 0;
		}
		case 'build':
			none(rest, 'changelog build');
			writeChangelog(root);
			out.log(`release: ${FILES.built} built`);
			return 0;
		case 'preview': {
			none(rest, 'changelog preview');
			const fragments = fragmentsOrFail(root);
			const heading = `## ${readMetadata(root).version} — unreleased`;
			out.log(
				fragments.length
					? releaseSection(heading, fragments).trimEnd()
					: `${heading}\n\nNo fragments in ${FILES.unreleased}/ yet.`,
			);
			return 0;
		}
		case 'notes':
			out.log(releaseNotes(root, single(rest, 'changelog notes TAG')).trimEnd());
			return 0;
		default:
			throw new ReleaseError('usage: changelog new|build|preview|notes …');
	}
}

export function run(argv, { root = defaultRoot(), out = console } = {}) {
	const print = { log: out.log, error: out.error };
	const [command, ...args] = argv;
	try {
		switch (command) {
			case 'check':
				return commandCheck(root, args, print);
			case 'version': {
				const version = single(args, 'version VERSION');
				setVersion(root, version);
				print.log(`release: version ${version} written; run npm run release -- check`);
				return 0;
			}
			case 'open': {
				const version = single(args, 'open VERSION');
				openVersion(root, version);
				print.log(`release: ${version}~alpha opened`);
				print.log(`  git commit -am "chore(release): open ${version}"`);
				return 0;
			}
			case 'cut': {
				let date = today();
				if (args.length === 2 && args[0] === '--date') {
					date = args[1];
				} else {
					none(args, 'cut [--date YYYY-MM-DD]');
				}
				return cut(root, date, print);
			}
			case 'changelog':
				return changelog(root, args, print);
			default:
				throw new ReleaseError('usage: release.mjs check|version|open|cut|changelog …');
		}
	} catch (error) {
		if (error instanceof ReleaseError) {
			print.error(`release: ${error.message}`);
			return 1;
		}
		throw error;
	}
}

function defaultRoot() {
	return process.env.RELEASE_ROOT || join(dirname(fileURLToPath(import.meta.url)), '..');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	process.exitCode = run(process.argv.slice(2));
}
